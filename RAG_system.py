"""#Split PDF into Chunks"""

def PDF_Splitter(path):
  chunks=partition_pdf(
      filename=path,
      infer_table_structure=True,
      chunking_strategy="by_title",
      max_characters=2000,
      extract_image_block_types=["Image"],
      extraxt_images_in_pdf=True

  )
  return chunks

"""#Separating the extracted data into Text , Images & Tables"""

def Extract_data(chunks):
  Images=[]
  Text=[]
  Tables=[]
  for chunk in chunks:
    if "Table" in str(type(chunk)):
      Tables.append(chunk)
    if "CompositeElement" in str(type(chunk)):
      Text.append(chunk)
      meta_data=chunk.metadata.orig_elements
      for data in meta_data:
        if "Image" in str(type(data)):
          Images.append(data.metadata.image_path)
  return Text , Tables , Images

"""#Store the Embedding vectors into Chroma DB"""

def create_vector_db(Text, Tables, Images):
    client = chromadb.Client()
    text_embedding = SentenceTransformerEmbeddingFunction(model_name="all-MiniLM-L6-v2")
    text_collection = client.get_or_create_collection(
        name="text",
        embedding_function=text_embedding
    )
    data_loader = ImageLoader()

    text_strings = [str(chunk.text) for chunk in Text]
    table_strings = [str(tbl) for tbl in Tables]
    all_texts = text_strings + table_strings

    text_collection.add(
        ids=[f"text_{i}" for i in range(len(all_texts))],
        documents=all_texts
    )

    image_embedding = OpenCLIPEmbeddingFunction()

    image_collection = client.get_or_create_collection(
        name="image",
        embedding_function=image_embedding,
        data_loader=data_loader
    )



    image_collection.add(
        ids=[f"image_{i}" for i in range(len(Images))],
        uris=Images,
        metadatas=[{"file": path} for path in Images]
    )

    return text_collection, image_collection

