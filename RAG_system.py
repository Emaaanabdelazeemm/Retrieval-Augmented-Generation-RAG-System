from IPython.display import Image, display

def asking_question(query, db, images_db, llm):
    text_results = db.query(
        query_texts=[query],
        n_results=3,
        include=["documents"]
    )
    retrieved_texts = text_results.get("documents", [[]])[0]
    context = "\n".join(retrieved_texts) if retrieved_texts else ""

    prompt = f"""
Use the context to answer the user's question.

Context:
{context}

Question: {query}
Answer:"""

    retrieved_images = []
    if images_db is not None:
        img_results = images_db.query(
            query_texts=[query],
            n_results=1,
            include=["metadatas"]
        )
        metas = img_results.get("metadatas", [[]])[0]
        if metas:
            retrieved_images = [m.get("file", "unknown") for m in metas]
            image_info = ", ".join(retrieved_images)
            prompt += f"\n\nRelated images (filenames): {image_info}"
    answer = llm.invoke(prompt).content
    print(answer)
    if retrieved_images:
        print("\n Related images:")
        for img_path in retrieved_images:
            try:

                display(Image(filename=img_path))
            except Exception as e:
                print(f"Could not display {img_path}: {e}")

    return answer

